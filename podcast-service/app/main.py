# Voice-over job storage (separate from podcast jobs)
voiceover_jobs: Dict[str, Dict[str, Any]] = {}


class VoiceOverRequest(BaseModel):
    text: str
    voice: str = "female"  # "male" or "female"
    pronunciationRules: Optional[List[Dict[str, str]]] = None
    ttsEngine: Optional[str] = None


class VoiceOverResponse(BaseModel):
    job_id: str
    status: str
    message: str


async def process_voiceover(
    job_id: str,
    text: str,
    voice: str,
    pronunciation_rules: Optional[List[Dict[str, str]]] = None,
    tts_engine: Optional[str] = None,
):
    """Background task to generate voice-over audio."""
    try:
        voiceover_jobs[job_id]["status"] = "processing"
        voiceover_jobs[job_id]["current_stage"] = "Audio wird generiert..."
        voiceover_jobs[job_id]["progress"] = 5

        output_path = os.path.join(OUTPUT_DIR, f"voiceover_{job_id}.mp3")

        def progress_callback(percent, stage):
            voiceover_jobs[job_id]["progress"] = percent
            voiceover_jobs[job_id]["current_stage"] = stage

        # Run TTS generation in thread pool
        import asyncio
        loop = asyncio.get_event_loop()
        result = await loop.run_in_executor(
            None,
            lambda: generate_voiceover(
                text=text,
                voice=voice,
                pronunciation_rules=pronunciation_rules,
                output_path=output_path,
                progress_callback=progress_callback,
                tts_engine=tts_engine,
            )
        )

        if not result.get("success"):
            raise ValueError(result.get("error", "Voice-Over Generierung fehlgeschlagen"))

        voiceover_jobs[job_id]["status"] = "completed"
        voiceover_jobs[job_id]["current_stage"] = "Fertig"
        voiceover_jobs[job_id]["progress"] = 100
        voiceover_jobs[job_id]["completed_at"] = datetime.utcnow().isoformat()
        voiceover_jobs[job_id]["output_path"] = output_path
        voiceover_jobs[job_id]["duration_seconds"] = result.get("duration_seconds", 0)

    except Exception as e:
        voiceover_jobs[job_id]["status"] = "failed"
        voiceover_jobs[job_id]["error"] = str(e)
        voiceover_jobs[job_id]["current_stage"] = "Fehler"
        print(f"[VoiceOver] Job {job_id} failed: {e}")


@app.post("/voiceover/generate", response_model=VoiceOverResponse)
async def generate_voiceover_endpoint(
    background_tasks: BackgroundTasks,
    request: VoiceOverRequest,
):
    """
    Generate voice-over audio from text.

    - **text**: Text to synthesize (max 50,000 characters)
    - **voice**: "male" or "female"
    - **pronunciationRules**: Optional list of {"original": "...", "spoken": "..."} rules
    """
    if not request.text or not request.text.strip():
        raise HTTPException(status_code=400, detail="Kein Text angegeben")

    if len(request.text) > 50000:
        raise HTTPException(status_code=400, detail="Text zu lang (max. 50.000 Zeichen)")

    if request.voice not in ("male", "female"):
        raise HTTPException(status_code=400, detail="Ungueltige Stimme. Erlaubt: male, female")

    if request.ttsEngine:
        valid_engines = {"xtts", "qwen3tts", "piper"}
        if request.ttsEngine.lower() not in valid_engines:
            raise HTTPException(status_code=400, detail="Ungueltige TTS-Engine")

    job_id = str(uuid.uuid4())

    voiceover_jobs[job_id] = {
        "job_id": job_id,
        "status": "pending",
        "progress": 0,
        "current_stage": "In Warteschlange...",
        "created_at": datetime.utcnow().isoformat(),
        "completed_at": None,
        "error": None,
        "output_path": None,
        "duration_seconds": None,
        "voice": request.voice,
        "text_length": len(request.text),
    }

    background_tasks.add_task(
        process_voiceover,
        job_id,
        request.text,
        request.voice,
        request.pronunciationRules,
        request.ttsEngine,
    )

    return VoiceOverResponse(
        job_id=job_id,
        status="pending",
        message="Voice-Over Generierung gestartet",
    )



@app.get("/voiceover/download/{job_id}")
async def download_voiceover(job_id: str):
    """Download the completed voice-over audio file."""
    if job_id not in voiceover_jobs:
        raise HTTPException(status_code=404, detail="Job nicht gefunden")

    job = voiceover_jobs[job_id]

    if job["status"] != "completed":
        raise HTTPException(
            status_code=400,
            detail=f"Voice-Over nicht bereit. Status: {job['status']}"
        )

    output_path = job.get("output_path")
    if not output_path or not os.path.exists(output_path):
        raise HTTPException(status_code=404, detail="Datei nicht gefunden")

    return FileResponse(
        path=output_path,
        media_type="audio/mpeg",
        filename="voiceover.mp3",
    )


@app.post("/voiceover/extract-text")
async def extract_text_endpoint(file: UploadFile = File(...)):
    """
    Extract text from a Word document (.docx).

    - **file**: Word document file (.docx)
    """
    if not file.filename:
        raise HTTPException(status_code=400, detail="Dateiname erforderlich")

    ext = file.filename.lower().split(".")[-1]
    if ext not in ["docx", "doc"]:
        raise HTTPException(
            status_code=400,
            detail=f"Ungueltiger Dateityp: {ext}. Unterstuetzt: DOCX"
        )

    # Save file temporarily
    temp_path = os.path.join(UPLOAD_DIR, f"temp_{uuid.uuid4()}_{file.filename}")

    try:
        content = await file.read()
        with open(temp_path, "wb") as f:
            f.write(content)

        # Extract text
        result = extract_text_from_docx(temp_path)

        if not result.get("success"):
            raise HTTPException(status_code=400, detail=result.get("error", "Extraktion fehlgeschlagen"))

        return {
            "text": result["text"],
            "word_count": result["word_count"],
            "paragraph_count": result["paragraph_count"],
            "metadata": result.get("metadata", {}),
        }

    finally:
        # Cleanup
        if os.path.exists(temp_path):
            os.remove(temp_path)



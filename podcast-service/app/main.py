# In-memory job storage
jobs: Dict[str, Dict[str, Any]] = {}
PODCAST_DISFLUENCIES = os.getenv("PODCAST_DISFLUENCIES", "false").lower() == "true"

TTS_PRESET_INSTRUCTS: Dict[str, str] = {
    "klar": "Sprich ruhig, klar und praezise in Hochdeutsch mit gleichmaessigem Tempo.",
    "lebendig": "Sprich lebendig, natuerlich und warm in Hochdeutsch mit sinnvollen Pausen.",
    "dynamisch": "Sprich dynamisch und energiegeladen in Hochdeutsch mit variierter Betonung.",
}


def resolve_tts_instruct(tts_preset: Optional[str]) -> Optional[str]:
    if not tts_preset:
        return None
    return TTS_PRESET_INSTRUCTS.get(tts_preset)



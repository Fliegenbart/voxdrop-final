# Cleanup old jobs periodically
@app.on_event("startup")
async def startup():
    """Cleanup old files and preload XTTS model on startup."""
    # Cleanup old output files
    try:
        import time
        now = time.time()
        for f in os.listdir(OUTPUT_DIR):
            path = os.path.join(OUTPUT_DIR, f)
            if os.path.isfile(path):
                age = now - os.path.getmtime(path)
                if age > 24 * 60 * 60:
                    os.remove(path)
    except Exception as e:
        print(f"[Podcast] Cleanup error: {e}")

    # Preload XTTS model in background to avoid slow first request
    import asyncio
    asyncio.create_task(_preload_xtts())


async def _preload_xtts():
    """Preload XTTS model in background."""
    import asyncio
    from app.config import TTS_ENGINE

    if TTS_ENGINE != "xtts" or os.getenv("XTTS_PRELOAD", "true").lower() != "true":
        print("[Podcast] TTS engine is not XTTS, skipping preload")
        return

    print("[Podcast] Preloading XTTS model...")
    try:
        # Run model loading in thread pool to not block event loop
        loop = asyncio.get_event_loop()
        await loop.run_in_executor(None, _load_xtts_model)
        print("[Podcast] XTTS model preloaded successfully")
    except Exception as e:
        print(f"[Podcast] XTTS preload failed: {e}")


def _load_xtts_model():
    """Load XTTS model (runs in thread pool)."""
    from app.generators.xtts_generator import get_xtts_generator
    xtts = get_xtts_generator()
    if xtts.is_available():
        # Force initialization
        xtts._ensure_initialized()

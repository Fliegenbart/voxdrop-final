@app.get("/download/{job_id}")
async def download_podcast(job_id: str):
    """Download the completed podcast file."""
    if job_id not in jobs:
        raise HTTPException(status_code=404, detail="Job nicht gefunden")

    job = jobs[job_id]

    if job["status"] != "completed":
        raise HTTPException(
            status_code=400,
            detail=f"Podcast nicht bereit. Status: {job['status']}"
        )

    output_path = job.get("output_path")
    if not output_path or not os.path.exists(output_path):
        raise HTTPException(status_code=404, detail="Datei nicht gefunden")

    # Generate nice filename
    original_name = job.get("filename", "podcast")
    base_name = original_name.rsplit(".", 1)[0]
    download_name = f"{base_name}_podcast.mp3"

    return FileResponse(
        path=output_path,
        media_type="audio/mpeg",
        filename=download_name,
    )



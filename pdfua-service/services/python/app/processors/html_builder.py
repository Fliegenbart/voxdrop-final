def _structured_used_indices(slide: Dict[str, Any]) -> set[int]:
    explicit = slide.get("structured_used_indices")
    if isinstance(explicit, list):
        used: set[int] = set()
        for value in explicit:
            try:
                used.add(int(value))
            except Exception:
                continue
        return used

    used: set[int] = set()
    for item in slide.get("structured_items", []) or []:
        for idx in item.get("source_indices", []) or []:
            try:
                used.add(int(idx))
            except Exception:
                continue
    return used


def _anchor_id(slide_num: int) -> str:
    return f"slide-{slide_num}"


def _build_outline_html(slides: List[Dict[str, Any]], labels: Dict[str, str], lang: str) -> List[str]:
    if not slides:
        return []

    toc_label = labels.get("toc", "Inhaltsverzeichnis")
    parts = [
        f'    <nav class="document-outline" aria-label="{escape(toc_label)}" role="doc-toc">',
        f'      <h2 class="toc-title">{escape(toc_label)}</h2>',
        '      <ol>',
    ]

    for slide in slides:
        slide_num = int(slide.get("slide_number") or 0)
        if slide_num <= 0:
            continue
        title_text = cleanup_llm_artifacts(str(slide.get("title") or "").strip())
        if not title_text:
            title_text = f"{labels['slide']} {slide_num}"
        anchor = _anchor_id(slide_num)
        aria_text = f'{labels["slide"]} {slide_num}: {title_text}'
        # Show a human-friendly TOC entry, but avoid the literal "Folie {n}: ..." prefix
        # to prevent the Java bookmark resolver from matching TOC text instead of the slide page.
        visible_title = cleanup_llm_artifacts(title_text).strip()
        visible_title = re.sub(r"^folie\s*\d+\s*:\s*", "", visible_title, flags=re.IGNORECASE).strip()
        if not visible_title:
            visible_title = "Ohne Titel"
        link_text = f'{slide_num}: {format_text(visible_title, lang)}'
        parts.append(
            # title attribute is a good signal for converters to populate PDF annotation /Contents.
            f'        <li><a href="#{anchor}" aria-label="{escape(aria_text)}" title="{escape(aria_text)}">{link_text}</a></li>'
        )

    parts.extend([
        '      </ol>',
        '    </nav>',
    ])

    return parts


def _ordered_text_blocks(slide: Dict[str, Any]) -> List[Dict[str, Any]]:
    blocks = slide.get("text_ordered") or slide.get("text_content") or []
    if not blocks:
        return []

    if slide.get("text_ordered"):
        return list(blocks)

    if any("top_norm" in b for b in blocks):
        return sorted(
            blocks,
            key=lambda b: (
                float(b.get("top_norm") or 0.0),
                float(b.get("left_norm") or 0.0),
            ),
        )

    return list(blocks)


def _build_structured_items_html(slide: Dict[str, Any], labels: Dict[str, str]) -> tuple[List[str], set[int]]:
    items = slide.get("structured_items") or []
    if not items:
        return [], set()

    used_indices = _structured_used_indices(slide)
    parts: List[str] = [
        f'        <section class="structured-items" aria-label="{escape(labels["structured_items"])}">',
        f'          <h3 class="structured-items-title">{escape(labels["structured_items"])}</h3>',
        '          <ol class="structured-items-list">',
    ]

    for item in items:
        number = str(item.get("number") or "").strip()
        heading = cleanup_llm_artifacts(str(item.get("heading") or "").strip())
        body_parts = [
            cleanup_llm_artifacts(str(text).strip())
            for text in (item.get("body") or [])
            if str(text).strip()
        ]
        body = " ".join(body_parts)

        prefix = f"{number}. " if number else ""
        parts.append('            <li class="structured-item">')
        if heading:
            parts.append(
                f'              <p class="structured-heading"><strong>{escape(prefix + heading)}</strong></p>'
            )
        elif number:
            parts.append(
                f'              <p class="structured-heading"><strong>{escape(prefix)}</strong></p>'
            )

        if body:
            parts.append(f'              <p class="structured-body">{escape(body)}</p>')

        parts.append('            </li>')

    parts.extend([
        '          </ol>',
        '        </section>',
    ])

    return parts, used_indices


def _infer_table_from_blocks(
    blocks: List[Dict[str, Any]],
    skip_indices: Optional[Set[int]] = None,
) -> tuple[List[List[str]], set[int], Dict[str, Any]]:
    """Infer simple tables from aligned text blocks."""
    if not blocks:
        return [], set(), {"accepted": False, "classification_source": "heuristic", "reason": "no_blocks"}
    if not any("top_norm" in b and "left_norm" in b for b in blocks):
        return [], set(), {"accepted": False, "classification_source": "heuristic", "reason": "missing_layout"}
    skip_indices = set(skip_indices or set())

    # Cluster rows by vertical position.
    row_tol = 0.035
    rows: List[Dict[str, Any]] = []
    for block in sorted(blocks, key=lambda b: float(b.get("top_norm") or 0.0)):
        top = float(block.get("top_norm") or 0.0)
        placed = False
        for row in rows:
            if abs(top - row["mean_top"]) <= row_tol:
                row["blocks"].append(block)
                row["mean_top"] = sum(float(b.get("top_norm") or 0.0) for b in row["blocks"]) / max(len(row["blocks"]), 1)
                placed = True
                break
        if not placed:
            rows.append({"mean_top": top, "blocks": [block]})

    if len(rows) < 2:
        return [], set(), {"accepted": False, "classification_source": "heuristic", "reason": "too_few_rows"}

    # Cluster columns by horizontal position.
    col_tol = 0.08
    col_centers: List[float] = []
    for row in rows:
        for block in row["blocks"]:
            left = float(block.get("left_norm") or 0.0)
            placed = False
            for idx, center in enumerate(col_centers):
                if abs(left - center) <= col_tol:
                    col_centers[idx] = (center + left) / 2.0
                    placed = True
                    break
            if not placed:
                col_centers.append(left)

    col_centers = sorted(col_centers)
    if len(col_centers) < 2:
        return [], set(), {"accepted": False, "classification_source": "heuristic", "reason": "single_column"}

    table_rows: List[List[str]] = []
    used_indices: set[int] = set()
    multi_col_rows = 0

    for row in sorted(rows, key=lambda r: r["mean_top"]):
        cells = [""] * len(col_centers)
        for block in sorted(row["blocks"], key=lambda b: float(b.get("left_norm") or 0.0)):
            left = float(block.get("left_norm") or 0.0)
            col_idx = min(range(len(col_centers)), key=lambda i: abs(col_centers[i] - left))
            idx = block.get("index")
            if isinstance(idx, int) and idx in skip_indices:
                continue
            content = str(block.get("content") or "").strip()
            if not content:
                continue
            cells[col_idx] = content
            if isinstance(idx, int):
                used_indices.add(idx)
        if sum(1 for cell in cells if cell.strip()) >= 2:
            multi_col_rows += 1
        table_rows.append(cells)

    if multi_col_rows < 2:
        return [], set(), {"accepted": False, "classification_source": "heuristic", "reason": "no_grid"}

    non_empty_rows = [[cell for cell in row if cell.strip()] for row in table_rows if any(cell.strip() for cell in row)]
    if len(non_empty_rows) < 2:
        return [], set(), {"accepted": False, "classification_source": "heuristic", "reason": "too_few_content_rows"}

    header_cells = non_empty_rows[0]
    header_keywords = ("jahr", "wert", "status", "thema", "rolle", "bereich", "phase", "ziel", "kategorie", "maßnahme")
    has_keyword_header = any(any(keyword in cell.lower() for keyword in header_keywords) for cell in header_cells)
    short_header_cells = sum(1 for cell in header_cells if len(cell) <= 42 and not cell.endswith((".", "?", "!")))
    second_row = non_empty_rows[1]
    numeric_second_row = any(KPI_VALUE_RE.search(cell) for cell in second_row)
    header_evidence = (
        len(non_empty_rows) >= 3
        and len(header_cells) >= 2
        and short_header_cells >= 2
        and (has_keyword_header or numeric_second_row or len(non_empty_rows) >= 4)
    )

    if not header_evidence:
        return [], set(), {"accepted": False, "classification_source": "heuristic", "reason": "missing_header_evidence"}

    return table_rows, used_indices, {"accepted": True, "classification_source": "heuristic", "reason": None}


def _append_risk_flag(slide: Dict[str, Any], flag: str) -> None:
    if not flag:
        return
    risk_flags = slide.setdefault("risk_flags", [])
    if isinstance(risk_flags, list) and flag not in risk_flags:
        risk_flags.append(flag)


def build_html(
    slides: List[Dict[str, Any]],
    document_title: str,
    lang: str = "de",
    output_mode: str = "narrative_summary",
) -> str:
    """
    Build semantic HTML from parsed slides.

    The HTML is structured for OpenHTMLtoPDF to convert to PDF/UA:
    - Each slide becomes a section with page break
    - Headings follow hierarchy (h1 for slide titles)
    - Images have alt text
    - Tables have proper structure
    """
    # Clean document title
    lang = normalize_lang(lang)
    title = escape(document_title.rsplit(".", 1)[0])
    labels = _get_labels(lang)

    html_parts = [
        '<!DOCTYPE html>',
        f'<html lang="{escape(lang)}">',
        '<head>',
        f'  <title>{title}</title>',
        '  <meta charset="UTF-8">',
        '  <meta name="viewport" content="width=device-width, initial-scale=1.0">',
        '  <style>',
        get_css_styles(),
        '  </style>',
        '</head>',
        '<body>',
        f'  <header role="banner">',
        f'    <h1 class="document-h1" role="doc-title">{title}</h1>',
        f'  </header>',
        '  <main role="main">',
    ]

    if GENERATE_TOC:
        html_parts.extend(_build_outline_html(slides, labels, lang))

    # Process each slide
    appendix_start = _find_appendix_start(slides)
    for idx, slide in enumerate(slides):
        if appendix_start is not None and idx == appendix_start:
            html_parts.extend([
                '    <section class="appendix">',
                '      <h1 class="slide-title appendix-title">Anhang</h1>',
                '      <p>Die folgenden Folien enthalten ergänzende Detailinformationen.</p>',
                '    </section>',
            ])
        # Slide titles remain <h1 class="slide-title"> for bookmark extraction in the Java service.
        is_appendix = appendix_start is not None and idx >= appendix_start
        offset = 0
        slide_html = build_slide_html_v2(
            slide,
            lang,
            slides,
            heading_offset=offset,
            is_appendix=is_appendix,
            output_mode=output_mode,
        )
        html_parts.append(slide_html)

    html_parts.extend([
        '  </main>',
        '</body>',
        '</html>',
    ])

    return '\n'.join(html_parts)



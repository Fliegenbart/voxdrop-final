def normalize_lang(lang: Optional[str]) -> str:
    """Normalize language tag to IETF format for PDF/UA."""
    if not lang:
        return "de-DE"
    value = str(lang).replace("_", "-").strip()
    if not value:
        return "de-DE"
    lower = value.lower()
    if "-" not in value:
        if lower == "de":
            return "de-DE"
        if lower == "en":
            return "en-US"
    return value


def convert_umlauts(text: str) -> str:
    """
    Keep umlauts intact. We rely on UTF-8 throughout the pipeline.
    """
    if not text:
        return ""
    return str(text)


def cleanup_llm_artifacts(text: str) -> str:
    """
    Remove technical LLM artifacts from generated text.

    Common artifacts include special tokens, markdown formatting,
    and other model-specific markers that shouldn't appear in output.
    """
    if not text:
        return ""

    # Known LLM markers to remove
    artifacts = [
        "<|end|>",
        "<|im_end|>",
        "<|im_start|>",
        "<|assistant|>",
        "<|user|>",
        "<|system|>",
        "[/INST]",
        "[INST]",
        "<<SYS>>",
        "<</SYS>>",
        "```",
        "---",
        "<end_of_turn>",
        "<start_of_turn>",
    ]

    result = text
    for artifact in artifacts:
        result = result.replace(artifact, "")

    # Remove any remaining angle-bracket tokens like <|...|>
    result = re.sub(r'<\|[^|]+\|>', '', result)

    # Normalize PPTX soft line breaks and whitespace
    result = (
        result.replace("\v", "\n")
        .replace("\x0b", "\n")
        .replace("\x0c", "\n")
        .replace("\u2028", "\n")
        .replace("\u2029", "\n")
    )
    result = re.sub(r'\n{3,}', '\n\n', result)
    result = re.sub(r' {2,}', ' ', result)
    result = _fix_missing_spaces(result)

    return result.strip()


def _fix_missing_spaces(text: str) -> str:
    """Insert missing spaces caused by soft line breaks in PPTX exports."""
    if not text:
        return ""
    value = str(text)
    value = re.sub(r"([.!?:])([A-ZÄÖÜ])", r"\1 \2", value)
    value = re.sub(r"([a-zäöüß]{3,})([A-ZÄÖÜ])", r"\1 \2", value)
    value = re.sub(r"(\d)([A-ZÄÖÜ])", r"\1 \2", value)
    return value


def escape(text: str) -> str:
    """Escape HTML special characters while preserving umlauts."""
    if not text:
        return ""
    return html_escape(convert_umlauts(str(text)))


def format_text(text: str, lang: str) -> str:
    """Escape text and apply language spans when enabled."""
    cleaned = cleanup_llm_artifacts(text)
    if not cleaned:
        return ""
    if ENABLE_LANGUAGE_TAGGING:
        return apply_language_tags(cleaned)
    return escape(cleaned)


def _limit_sentences(text: str, max_sentences: int) -> str:
    if not text:
        return ""
    if max_sentences <= 0:
        return text
    parts = re.split(r"(?<=[.!?])\s+", text.strip())
    if len(parts) <= max_sentences:
        return text
    return " ".join(parts[:max_sentences]).strip()



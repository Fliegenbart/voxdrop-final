def _looks_generic_alt(text: str) -> bool:
    if not text:
        return True
    lowered = text.strip().lower()
    if lowered in {"abbildung", "grafik", "bild", "image"}:
        return True
    if "abbildung auf folie" in lowered or "bild auf folie" in lowered or "grafik auf folie" in lowered:
        return True
    if "image on slide" in lowered:
        return True
    if len(lowered) < 8:
        return True
    return False


def _is_redundant_alt(text: str, slide: Dict[str, Any]) -> bool:
    if not text:
        return False
    context_parts = []
    for key in ("slide_summary", "structured_text"):
        value = slide.get(key)
        if isinstance(value, str) and value.strip():
            context_parts.append(value.strip())
    context = " ".join(context_parts)
    if not context:
        return False
    overlap = overlap_ratio(text, context)
    return overlap >= 0.6 and not _looks_visual_text(text)


def _slide_context_snippet(slide: Dict[str, Any]) -> str:
    blocks = _ordered_text_blocks(slide)
    for block in blocks:
        content = str(block.get("content") or "").strip()
        if content:
            return cleanup_llm_artifacts(content).replace("\n", " ").strip()
    return ""


def _is_editorial_note(text: str) -> bool:
    lowered = text.strip().lower()
    if not lowered:
        return False
    markers = [
        "falls diese folie gewünscht",
        "redaktionelle notiz",
        "bitte entfernen",
        "nur intern",
    ]
    return any(marker in lowered for marker in markers)


def _fallback_summary(slide: Dict[str, Any]) -> str:
    """Build a short summary when LLM summary is missing."""
    candidates = []
    structured = str(slide.get("structured_text") or "").strip()
    if structured:
        candidates.append(structured)
    blocks = _ordered_text_blocks(slide)
    for block in blocks:
        content = str(block.get("content") or "").strip()
        if content:
            candidates.append(content)
        if len(candidates) >= 2:
            break
    combined = " ".join(candidates)
    combined = re.sub(r"\s+", " ", combined).strip()
    combined = _limit_sentences(combined, MAX_SUMMARY_SENTENCES)
    if combined:
        return combined
    title = str(slide.get("title") or "").strip() or f"Folie {slide.get('slide_number')}"
    return f"Diese Folie behandelt {title}."


def _safe_float(value: Any) -> float:
    try:
        return float(value or 0.0)
    except Exception:
        return 0.0


def _is_probably_small_icon(img: Dict[str, Any]) -> bool:
    area = _safe_float(img.get("area_norm"))
    width = _safe_float(img.get("width_norm"))
    height = _safe_float(img.get("height_norm"))
    if area <= 0.0:
        return False
    return area <= 0.03 and width <= 0.18 and height <= 0.18


def _collect_meaningful_image_descriptions(slide: Dict[str, Any]) -> List[str]:
    descriptions: List[str] = []
    for img in slide.get("images", []) or []:
        if img.get("decorative") or img.get("vision_class") == "decorative":
            continue

        area = _safe_float(img.get("area_norm"))
        width = _safe_float(img.get("width_norm"))
        height = _safe_float(img.get("height_norm"))
        large_enough = area >= 0.08 or (width >= 0.28 and height >= 0.18)
        if not large_enough:
            continue

        candidates = [
            img.get("alt_text"),
            img.get("vision_alt_text"),
            img.get("diagram_description"),
        ]
        chosen = ""
        for candidate in candidates:
            text = cleanup_llm_artifacts(str(candidate or "")).strip()
            if not text or _looks_generic_alt(text) or _is_generic_visual_hint(text):
                continue
            if _is_redundant_alt(text, slide):
                continue
            chosen = text
            break

        if not chosen:
            ocr_text = cleanup_llm_artifacts(str(img.get("vision_ocr_text") or img.get("ocr_text") or "")).strip()
            if len(ocr_text) >= 24:
                if len(ocr_text) > 200:
                    ocr_text = ocr_text[:197] + "..."
                chosen = f"Screenshot mit Text: {ocr_text}"

        if chosen:
            descriptions.append(chosen)

    return descriptions


def _build_visual_description(slide: Dict[str, Any]) -> str:
    """Create a visual description only when it adds real value."""
    if not INCLUDE_VISUAL_DESCRIPTIONS:
        return ""
    has_visual = bool(slide.get("images") or slide.get("has_chart") or slide.get("is_visual_diagram") or slide.get("diagram_summary"))
    if not has_visual:
        return ""

    description = ""
    diagram_summary = str(slide.get("diagram_summary") or "").strip()
    if diagram_summary and _looks_visual_text(diagram_summary):
        description = diagram_summary

    if not description:
        chart_summaries = []
        for shape in slide.get("shapes", []) or []:
            if shape.get("type") == "chart":
                summary = str(shape.get("summary") or "").strip()
                if summary:
                    chart_summaries.append(summary)
        if chart_summaries:
            description = " ".join(chart_summaries)

    if not description:
        informative_alts = _collect_meaningful_image_descriptions(slide)
        if informative_alts:
            description = " ".join(informative_alts)

    return description


def _extract_kpis(
    blocks: List[Dict[str, Any]],
    used_indices: set[int],
) -> tuple[List[tuple[str, str]], set[int]]:
    if not blocks:
        return [], set()

    rows: List[tuple[str, str]] = []
    used: set[int] = set()
    pending_label: Optional[str] = None

    for block in blocks:
        idx = block.get("index")
        if isinstance(idx, int) and idx in used_indices:
            continue
        content = cleanup_llm_artifacts(str(block.get("content") or "")).strip()
        if not content:
            continue
        lines = [line.strip() for line in content.split("\n") if line.strip()]
        for line in lines:
            if len(line) > 140:
                continue
            match = KPI_VALUE_RE.search(line)
            if not match:
                if len(line) <= 80:
                    pending_label = line
                continue
            value = match.group("value").strip()
            label = line.replace(match.group("value"), "").strip(" :–-")
            label = KPI_PREFIX_RE.sub("", label).strip(" :–-")
            if not label and pending_label:
                label = pending_label
            if not label:
                continue
            if YEAR_RANGE_RE.fullmatch(value) and len(label) <= 4:
                continue
            rows.append((label, value))
            if isinstance(idx, int):
                used.add(idx)
            pending_label = None

    deduped: List[tuple[str, str]] = []
    seen: set[str] = set()
    for label, value in rows:
        key = label.lower()
        if key in seen:
            continue
        seen.add(key)
        deduped.append((label, value))

    if len(deduped) < 2:
        return [], set()
    return deduped, used


def _timeline_rows(points: List[str]) -> List[tuple[str, str]]:
    rows: List[tuple[str, str]] = []
    for point in points:
        text = cleanup_llm_artifacts(str(point)).strip()
        if not text:
            continue
        match = YEAR_RANGE_RE.search(text)
        if not match:
            continue
        period = match.group(0).strip()
        description = text.replace(match.group(0), "").strip(" :–-")
        if not description:
            description = text
        rows.append((period, description))
    if len(rows) < 2:
        return []
    return rows


def _append_paragraphs_with_lists(parts: List[str], paragraphs: List[str], indent: str, lang: str) -> None:
    list_items: List[str] = []
    list_type: Optional[str] = None

    def _flush() -> None:
        nonlocal list_items, list_type
        if not list_items:
            return
        tag = "ol" if list_type == "ol" else "ul"
        parts.append(f"{indent}<{tag}>")
        for item in list_items:
            parts.append(f"{indent}  <li>{format_text(item, lang)}</li>")
        parts.append(f"{indent}</{tag}>")
        list_items = []
        list_type = None
    for para in paragraphs:
        if not para:
            continue
        if NUMBER_ONLY_RE.match(para.strip()):
            continue
        if NUMBERED_ITEM_RE.match(para):
            item = NUMBERED_ITEM_RE.sub("", para).strip()
            if list_type and list_type != "ol":
                _flush()
            list_type = "ol"
            list_items.append(item)
            continue
        if para.startswith(BULLET_PREFIXES):
            item = para.lstrip("".join(BULLET_PREFIXES)).strip()
            if list_type and list_type != "ul":
                _flush()
            list_type = "ul"
            list_items.append(item)
            continue
        if list_items:
            _flush()
        parts.append(f"{indent}<p>{format_text(para, lang)}</p>")
    if list_items:
        _flush()


def _normalize_title(title: str) -> str:
    text = re.sub(r"^folie\s*\d+\s*:\s*", "", str(title or ""), flags=re.IGNORECASE).strip()
    text = re.sub(r"\s+", " ", text).lower()
    return text


def _find_appendix_start(slides: List[Dict[str, Any]]) -> Optional[int]:
    if not BACKUP_SLIDES_AS_APPENDIX:
        return None
    keywords = ("fazit", "ausblick", "schluss", "vielen dank", "danke", "fragen")
    for idx, slide in enumerate(slides):
        title = str(slide.get("title") or "").lower()
        if any(key in title for key in keywords):
            if idx + 1 < len(slides):
                return idx + 1
            return None
    return None


def _match_slide_anchor(label: str, slides: List[Dict[str, Any]]) -> Optional[str]:
    if not label:
        return None
    normalized = _normalize_title(label)
    best_anchor = None
    best_score = 0.0
    for slide in slides:
        title = str(slide.get("title") or "").strip()
        if not title:
            continue
        slide_norm = _normalize_title(title)
        score = 0.0
        if normalized and normalized in slide_norm:
            score = 1.0
        else:
            score = overlap_ratio(normalized, slide_norm)
        if score > best_score:
            best_score = score
            best_anchor = _anchor_id(int(slide.get("slide_number") or 0))
    if best_score >= 0.45:
        return best_anchor
    return None


def _resolve_alt_text(img: Dict[str, Any], slide: Dict[str, Any], slide_num: int) -> tuple[str, bool]:
    # Decorative handling
    if img.get("decorative") or img.get("vision_class") == "decorative":
        return "", True
    if _is_probably_small_icon(img):
        ocr_text = str(img.get("vision_ocr_text") or img.get("ocr_text") or "").strip()
        alt_hint = str(img.get("alt_text") or img.get("vision_alt_text") or img.get("existing_alt_text") or "").strip()
        if not ocr_text and (not alt_hint or _looks_generic_alt(alt_hint)):
            return "", True

    candidates = [
        img.get("alt_text"),
        img.get("vision_alt_text"),
        img.get("diagram_description"),
        img.get("existing_alt_text"),
    ]
    for candidate in candidates:
        if candidate is None:
            continue
        text = str(candidate).strip()
        if not text:
            continue
        if _looks_generic_alt(text):
            continue
        if _is_redundant_alt(text, slide):
            continue
        if not _looks_visual_text(text) and (slide.get("has_chart") or slide.get("is_visual_diagram")):
            # Prefer visual descriptions for charts/diagrams.
            continue
        if not _looks_generic_alt(text):
            return text, False

    # Screenshots: prefer OCR context if available.
    ocr_text = str(img.get("vision_ocr_text") or img.get("ocr_text") or "").strip()
    if ocr_text:
        ocr_text = cleanup_llm_artifacts(ocr_text)
        if len(ocr_text) > 200:
            ocr_text = ocr_text[:197] + "..."
        return f"Screenshot mit Text: {ocr_text}", False

    # Build a short fallback from slide title (PDF/UA requires /Alt on figures).
    title = str(slide.get("title") or "").strip()
    if not title:
        title = f"Folie {slide_num}"
    alt = f"Grafik auf Folie {slide_num}: {title}"
    if len(alt) > 200:
        alt = alt[:197] + "..."
    return alt, False


def _is_generic_visual_hint(text: str) -> bool:
    lowered = text.strip().lower()
    if not lowered:
        return True
    generic_patterns = (
        "enthält: diagramm",
        "enthält: grafik",
        "enthält: tabelle",
        "enthält: infografik",
        "contains: diagram",
        "contains: table",
    )
    return any(pattern in lowered for pattern in generic_patterns)


def _looks_visual_text(text: str) -> bool:
    lowered = text.lower()
    return any(keyword in lowered for keyword in VISUAL_KEYWORDS)


def _merge_number_fragments(blocks: List[Dict[str, Any]]) -> tuple[List[Dict[str, Any]], set[int]]:
    """
    Merge isolated numeric fragments (e.g., "1.", "2.") into the nearest text block.
    Returns updated blocks and a set of indices to skip.
    """
    if not blocks:
        return blocks, set()

    skip_indices: set[int] = set()

    for i, block in enumerate(blocks):
        content = str(block.get("content") or "").strip()
        if not content or not NUMBER_ONLY_RE.match(content):
            continue

        top = float(block.get("top_norm") or 0.0)
        left = float(block.get("left_norm") or 0.0)
        best = None
        best_dist = 1e9

        for j, candidate in enumerate(blocks):
            if j == i:
                continue
            cand_text = str(candidate.get("content") or "").strip()
            if not cand_text:
                continue
            cand_top = float(candidate.get("top_norm") or 0.0)
            cand_left = float(candidate.get("left_norm") or 0.0)
            # Same row and to the right
            if abs(cand_top - top) > 0.04:
                continue
            if cand_left <= left:
                continue
            dist = (cand_left - left) + abs(cand_top - top)
            if dist < best_dist:
                best_dist = dist
                best = candidate

        if best:
            prefix = content.strip()
            cand_text = str(best.get("content") or "")
            if not cand_text.strip().startswith(prefix):
                best["content"] = f"{prefix} {cand_text}".strip()
            idx = block.get("index")
            if isinstance(idx, int):
                skip_indices.add(idx)
            block["_skip_number_fragment"] = True

    return blocks, skip_indices


def build_image_html(img: Dict[str, Any], slide: Dict[str, Any], slide_num: int) -> str:
    """Build HTML for an image with alt text."""
    alt_text, decorative = _resolve_alt_text(img, slide, slide_num)
    if not alt_text and not decorative:
        title = str(slide.get("title") or "").strip() or f"Folie {slide_num}"
        alt_text = f"Grafik auf Folie {slide_num}: {title}"

    # Cleanup LLM artifacts and escape for HTML attribute
    alt_text = cleanup_llm_artifacts(alt_text or "")
    alt_text = escape(alt_text)

    # Get data URI for embedding
    data_uri = img.get("data_uri", "")

    # Calculate reasonable display size (max 600px width)
    width = img.get("width_inches", 0) * 96  # Convert to pixels
    if width > 600:
        width = 600

    height = img.get("height_inches", 0) * 96
    # Keep a visible box even when PPTX metadata is missing.
    if height <= 0:
        height = max(120, min(360, width * 0.6 if width else 180))

    if decorative:
        # World-class PDF/UA: decorative visuals should not appear as /Figure at all.
        # Rendering as CSS background keeps the visual output but avoids an <img> tag
        # that would create a Figure in the structure tree.
        return f'''      <div class="image-block decorative-image" role="presentation" aria-hidden="true"
        style="width: {int(width)}px; height: {int(height)}px; background-image: url('{data_uri}'); background-repeat: no-repeat; background-position: center; background-size: contain;">
      </div>'''

    return f'''      <div class="image-block">
        <img src="{data_uri}" alt="{alt_text}" style="max-width: {width}px; height: auto;">
      </div>'''


def build_table_html(table_data: Dict[str, Any], lang: str = "de") -> str:
    """Build accessible HTML table with merged-cell and column-width support.

    Cells may be plain strings (legacy) **or** dicts with keys
    ``text``, ``colspan``, ``rowspan``.  Both formats are handled
    transparently so existing callers keep working.
    """
    rows = table_data.get("rows", [])
    if not rows:
        return ""

    def _cell_text(cell) -> str:
        """Return display text regardless of cell format."""
        if isinstance(cell, dict):
            return cell.get("text", "")
        return cell if str(cell).strip() else ""

    def _cell_span(cell, attr: str) -> int:
        if isinstance(cell, dict):
            return int(cell.get(attr, 1))
        return 1

    def _span_attrs(cell) -> str:
        """Return colspan/rowspan HTML attributes when > 1."""
        parts = []
        cs = _cell_span(cell, "colspan")
        rs = _cell_span(cell, "rowspan")
        if cs > 1:
            parts.append(f' colspan="{cs}"')
        if rs > 1:
            parts.append(f' rowspan="{rs}"')
        return "".join(parts)

    summary = str(table_data.get("summary") or "").strip()
    summary_attr = f' summary="{escape(summary)}"' if summary else ""
    parts = [f'      <table{summary_attr}>']

    # Optional <colgroup> with relative widths
    col_widths = table_data.get("col_widths") or []
    if col_widths:
        parts.append('        <colgroup>')
        for w in col_widths:
            pct = round(w * 100, 1)
            parts.append(f'          <col style="width: {pct}%">')
        parts.append('        </colgroup>')

    # First row as header
    if rows:
        parts.append('        <thead>')
        parts.append('          <tr>')
        for cell in rows[0]:
            text = _cell_text(cell)
            spans = _span_attrs(cell)
            parts.append(f'            <th scope="col"{spans}>{format_text(text, lang)}</th>')
        parts.append('          </tr>')
        parts.append('        </thead>')

    # Remaining rows as body
    if len(rows) > 1:
        parts.append('        <tbody>')
        for row in rows[1:]:
            parts.append('          <tr>')
            for i, cell in enumerate(row):
                text = _cell_text(cell)
                spans = _span_attrs(cell)
                if i == 0:
                    parts.append(f'            <th scope="row"{spans}>{format_text(text, lang)}</th>')
                else:
                    parts.append(f'            <td{spans}>{format_text(text, lang)}</td>')
            parts.append('          </tr>')
        parts.append('        </tbody>')

    parts.append('      </table>')

    return '\n'.join(parts)


def build_chart_html(chart_data: Dict[str, Any], slide_num: int, lang: str = "de") -> str:
    """Build accessible HTML for a chart. Render as text (not <figure>) to avoid /Figure without /Alt."""
    chart_type_german = cleanup_llm_artifacts(chart_data.get("chart_type_german", "Diagramm"))
    chart_title = cleanup_llm_artifacts(chart_data.get("title", ""))
    summary = cleanup_llm_artifacts(chart_data.get("summary", ""))

    # Build description
    parts = []

    # Main title/type
    if chart_title:
        parts.append(f"{chart_type_german}: {chart_title}")
    else:
        parts.append(chart_type_german)

    # Use VLM summary if available
    if summary:
        parts.append(summary)
    else:
        # Generate description from data
        data_description = generate_chart_data_description(chart_data)
        if data_description:
            parts.append(data_description)

    description = " ".join(parts)

    caption_text = summary or generate_chart_data_description(chart_data) or "Diagramm mit Datenvisualisierung"
    title_html = f'<p class="chart-title">{format_text(chart_title, lang)}</p>' if chart_title else ''
    return f'''      <section class="chart" aria-label="{escape(description)}">
        <p class="chart-kind"><strong>{format_text(chart_type_german, lang)}</strong></p>
        {title_html}
        <p class="chart-summary">{format_text(caption_text, lang)}</p>
      </section>'''


def generate_chart_data_description(chart_data: Dict[str, Any]) -> str:
    """Generate a text description from chart data."""
    parts = []

    series_data = chart_data.get("series_data", [])
    categories = chart_data.get("categories", [])
    chart_type = chart_data.get("chart_type", "")

    # Describe categories if available
    if categories:
        if len(categories) <= 5:
            parts.append(f"Kategorien: {', '.join(str(c) for c in categories)}.")
        else:
            parts.append(f"{len(categories)} Kategorien von {categories[0]} bis {categories[-1]}.")

    # Describe series
    if series_data:
        for series in series_data[:3]:  # Limit to 3 series
            series_name = series.get("name")
            values = series.get("values", [])

            if series_name and values:
                # Calculate stats
                try:
                    numeric_values = [v for v in values if isinstance(v, (int, float))]
                    if numeric_values:
                        min_val = min(numeric_values)
                        max_val = max(numeric_values)

                        if "PIE" in chart_type or "DOUGHNUT" in chart_type:
                            # For pie charts, list percentages
                            total = sum(numeric_values)
                            if total > 0:
                                percentages = [(v / total * 100) for v in numeric_values[:5]]
                                parts.append(f"{series_name}: Werte von {min_val:.0f} bis {max_val:.0f}.")
                        else:
                            parts.append(f"{series_name}: Werte von {min_val:.0f} bis {max_val:.0f}.")
                except Exception:
                    pass

    return " ".join(parts) if parts else ""


def build_chart_placeholder(chart_data: Dict[str, Any], slide_num: int, lang: str = "de") -> str:
    """Build placeholder for chart (legacy fallback)."""
    return build_chart_html(chart_data, slide_num, lang)


